/**
 * Типы симуляционного движка реактора.
 * Модуль engine/ не зависит от React — чистая, детерминированная логика.
 */

/** Уровень сложности: как часто и как рано начинаются нештатные события. */
export type Difficulty = "easy" | "normal" | "hard";

/** Активное нештатное событие, влияющее на параметры симуляции. */
export interface ActiveEvent {
  id: string;
  /** Идентификатор сценария события из каталога EVENT_SCENARIOS. */
  scenarioId: string;
  title: string;
  description: string;
  /** Игровое время (сек) начала события. */
  startedAt: number;
  /** Сколько секунд у игрока есть на реакцию, прежде чем событие эскалирует. */
  reactionWindowSec: number;
  /** Отработано ли событие пользователем (например, выбрано корректирующее действие). */
  resolved: boolean;
}

/** Запись в журнале событий после завершения (истёк таймер либо решено пользователем). */
export interface EventLogEntry {
  id: string;
  /** Идентификатор сценария — нужен для проверки достижений по типу события. */
  scenarioId: string;
  title: string;
  /** Игровое время (сек) завершения. */
  endedAt: number;
  /** Сколько секунд прошло с появления события до его завершения. */
  reactionSec: number;
  outcome: "handled" | "missed";
}

/** Полное состояние симуляции на текущий тик. */
export interface ReactorState {
  /** Игровое время с начала смены, сек. */
  timeSec: number;

  /** Текущая мощность реактора, % (0–100). */
  power: number;
  /** Целевая мощность, к которой плавно движется power. */
  targetPower: number;

  /** Температура активной зоны, усл. °C. */
  temperature: number;
  /** Давление в контуре, усл. МПа. */
  pressure: number;
  /** Эффективность охлаждения, % (0–100). 100 — насосы работают штатно. */
  coolantFlow: number;

  /** Интегральный уровень безопасности, % (0–100). 0 — авария. */
  safety: number;

  /** Запас топлива, % (0–100). Расходуется тем быстрее, чем выше мощность;
   *  при низком запасе физически ограничивает достижимую мощность. */
  fuelLevel: number;

  /** Текущая выработка энергии, МВт. */
  energyOutput: number;
  /** Доля выработки, направляемая в город, % (0–100). */
  cityShare: number;
  /** Доля выработки, направляемая в промышленность = 100 - cityShare. */
  industryShare: number;
  /** Текущий спрос сети, МВт — меняется во времени. */
  gridDemand: number;

  /** Активные нештатные события. */
  activeEvents: ActiveEvent[];
  /** Журнал завершённых событий (последние — в конце массива). */
  eventLog: EventLogEntry[];

  /** Очки, накопленные за смену (этап 6). */
  score: number;

  /** Минимальный уровень безопасности за всю смену — для достижения «Идеальная смена». */
  minSafetySoFar: number;
  /** Сколько секунд подряд баланс выработки и спроса держится в допуске. */
  balanceStreakSec: number;

  /** Авария — состояние завершения смены с провалом. */
  isMeltdown: boolean;
  /** Смена завершена штатно — истекло время или пользователь нажал «Завершить смену». */
  isShiftComplete: boolean;

  /** Длительность смены, сек — обычная или ускоренная демо-версия (Этап 9). */
  shiftDurationSec: number;
  /** Демо-режим для питч-сессии: события начинаются раньше и идут чаще,
   *  независимо от выбранной сложности. */
  isDemo: boolean;
  /** Уровень сложности, выбранный перед стартом смены (игнорируется в демо-режиме). */
  difficulty: Difficulty;
}

/** Действия пользователя, применяемые на очередном тике. */
export interface UserActions {
  /** Новая целевая мощность, % (0–100). Undefined — без изменений. */
  setTargetPower?: number;
  /** Новое распределение энергии в город, % (0–100). Undefined — без изменений. */
  setCityShare?: number;
  /** Идентификаторы активных событий, отмеченных пользователем как «решено». */
  resolveEventIds?: string[];
  /** Ручная аварийная защита (АЗ): мгновенно (не плавно) роняет мощность
   *  до нуля ценой штрафа очков — как реальный сброс стержней СУЗ. */
  triggerScram?: boolean;
}

/** Пороговые зоны индикации для UI. */
export type IndicatorZone = "normal" | "warning" | "danger";

export interface Thresholds {
  normalMax: number;
  warningMax: number;
}
